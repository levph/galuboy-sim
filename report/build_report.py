def build_cover(rb, title: str, edition: str, date_text: str) -> None:
    """Replace the skill's default cover with one matching the reference
    reports under mimsarim/: org header + title block + 4x3 author table
    + date at bottom."""
    _clear_body(rb.doc)

    # --- Org header: single paragraph, 4 lines, size 48 bold ----------------
    p = rb.doc.add_paragraph()
    _make_bidi(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    lines = [
        'מחלקת לי"ד',
        "ענף תקשורת טקטית",
        "תחום הנדסת מערכות",
        "תקשורת ורשתות",
    ]
    for i, line in enumerate(lines):
        run = p.add_run(line)
        run.bold = True
        run.font.size = Pt(24)  # OOXML w:sz half-points → sz=48
        _set_run_fonts(run)
        if i < len(lines) - 1:
            run.add_break()

    rb.doc.add_paragraph()
    rb.doc.add_paragraph()

    # --- Title in 1x1 borderless table, size 72 bold ------------------------
    tbl = rb.doc.add_table(rows=1, cols=1)
    tbl.alignment = 1  # center
    _set_table_no_borders(tbl)
    cell = tbl.rows[0].cells[0]
    cell.text = ""
    p1 = cell.paragraphs[0]
    _make_bidi(p1)
    p1.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = p1.add_run(title)
    r1.bold = True
    r1.font.size = Pt(36)  # sz=72
    _set_run_fonts(r1)
    if edition:
        p2 = cell.add_paragraph()
        _make_bidi(p2)
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(edition)
        r2.bold = True
        r2.font.size = Pt(20)  # sz=40
        _set_run_fonts(r2)

    rb.doc.add_paragraph()
    rb.doc.add_paragraph()

    # --- Author table (4 rows × 3 cols), size 28 bold -----------------------
    authors = [
        ["דרגה", "שם",            "תפקיד"],
        ['קמ"א', "לב פנוב",       "כותב"],
        ['סא"ל', "תומר ברזילי",  "מבקר"],
        ['סא"ל', "יאיר כץ",       "מאשר"],
    ]
    atbl = rb.doc.add_table(rows=len(authors), cols=3)
    atbl.alignment = 1
    atbl.style = "Table Grid"
    bidiVisual = etree.SubElement(atbl._tbl.tblPr, qn("w:bidiVisual"))
    bidiVisual.set(qn("w:val"), "1")
    for ri, row in enumerate(authors):
        for ci, val in enumerate(row):
            cell = atbl.rows[ri].cells[ci]
            cell.text = ""
            cp = cell.paragraphs[0]
            _make_bidi(cp)
            cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
            cr = cp.add_run(val)
            cr.bold = True
            cr.font.size = Pt(14)  # sz=28
            _set_run_fonts(cr)

    # --- Spacer + date at bottom of cover -----------------------------------
    for _ in range(10):
        rb.doc.add_paragraph()
    pd = rb.doc.add_paragraph()
    _make_bidi(pd)
    pd.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rd = pd.add_run(date_text)
    rd.bold = True
    rd.font.size = Pt(18)  # sz=36
    _set_run_fonts(rd)

    rb.doc.add_page_break()
    rb._h1_seen = False  # so the first H1 doesn't trigger an extra page break


def _set_table_no_borders(tbl):
    """Remove borders from a python-docx table."""
    tblPr = tbl._tbl.tblPr
    borders = etree.SubElement(tblPr, qn("w:tblBorders"))
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = etree.SubElement(borders, qn(f"w:{edge}"))
        el.set(qn("w:val"), "nil")


def _update_footer_title(doc, new_title: str) -> None:
    """Replace the leftover template title in the page footer with the
    current report's title. The template's title is fragmented across the
    runs 'ניתוח פניות ', 'לקליטת חץ וקשת', ' בארגמן' inside one footer cell."""
    title_fragments = {"ניתוח פניות ", "לקליטת חץ וקשת", " בארגמן"}
    footer = doc.sections[0].footer
    for tbl in footer.tables:
        for row in tbl.rows:
            for cell in row.cells:
                cell_text_before = cell.text
                if "ארגמן" not in cell_text_before and "ניתוח פניות" not in cell_text_before:
                    continue
                # This is the title cell. Walk its runs: replace the first
                # title fragment with new_title, clear the remaining title
                # fragments, and leave any other runs (e.g. punctuation,
                # date pieces, page-number labels) untouched.
                first = True
                for p in cell.paragraphs:
                    for run in p.runs:
                        if run.text in title_fragments:
                            run.text = new_title if first else ""
                            first = False


def _justify_body_paragraphs(doc) -> int:
    """Switch body-text paragraphs from jc="right" to jc="both" (justified)."""
    fixed = 0
    body = doc.element.body
    for p in body:
        if p.tag != qn("w:p"):
            continue
        pPr = p.find(qn("w:pPr"))
        if pPr is None or pPr.find(qn("w:bidi")) is None:
            continue
        if pPr.find(qn("w:pStyle")) is not None:
            continue
        jc = pPr.find(qn("w:jc"))
        if jc is None or jc.get(qn("w:val")) != "right":
            continue
        first_run = p.find(qn("w:r"))
        if first_run is not None:
            rPr = first_run.find(qn("w:rPr"))
            if rPr is not None and rPr.find(qn("w:b")) is not None:
                continue
        jc.set(qn("w:val"), "both")
        fixed += 1
    return fixed


